/**
 * כללי כתיב עברי שהקוד צריך - **כרגע כלל אחד, וזה מספיק**.
 *
 * ## הבאג
 *
 * המחרוזת `` `ב${city.name}` `` מייצרת "בוינה". הכתיב הנכון בכתיב חסר
 * ניקוד הוא **"בווינה"**: אות שימוש שנוספת למילה שמתחילה בוי"ו עיצורית
 * מכפילה אותה. הקטלוג מחזיק שבעה שמות כאלה - וינה, ונציה, ורשה, וילנה,
 * וויוודינה, ואלה וזרמאט, וייטנאם - ווינה היא אחת מערי הדגל.
 *
 * זה מאותה משפחה של "כ-1 שעות" מרשומה (kk): המספר היה נכון, העברית לא,
 * ואף בדיקת טיפוסים או ולידטור לא יכולים לראות את זה. ההבדל הוא שהפעם
 * זה נתפס לפני שהגיע למסך - בכפתור "חיפוש לינה בוינה" של הפאנל החדש.
 *
 * ## למה פונקציה ולא תיקון בשמונה מקומות
 *
 * `ב${name}` מופיע היום ב-14 מקומות: תוויות נגישות, מציין מקום בשדה
 * חיפוש, שבבי הפעולה של הסוכן, כותרות ותיאורי עמוד. תיקון ידני היה
 * מחזיק עד הקריאה הבאה שמישהו יכתוב.
 */

/** אותיות השימוש שמכפילות וי"ו בתחילת מילה */
const PREFIXES = new Set(['ב', 'ל', 'כ', 'מ', 'ש', 'ה', 'ו', 'כש', 'לכש']);

/**
 * מצרף אות שימוש לשם.
 *
 * ```
 * hePrefix('ב', 'וינה')      // בווינה
 * hePrefix('ב', 'ברטיסלבה')  // בברטיסלבה
 * hePrefix('מ', 'ונציה')     // מוונציה
 * ```
 *
 * שם ריק מוחזר כמו שהוא ולא כאות בודדת - "ב" לבדה על המסך גרועה
 * מכלום.
 */
export function hePrefix(prefix: string, word: string): string {
  const w = (word ?? '').trim();
  if (!w) return '';
  if (!PREFIXES.has(prefix)) return `${prefix}${w}`;
  // וי"ו עיצורית בתחילת מילה מוכפלת אחרי אות שימוש. מילה שכבר פותחת
  // בשתי ווים ("וושינגטון") כבר כתובה נכון ואין מה להוסיף לה.
  if (w.startsWith('ו') && !w.startsWith('וו')) return `${prefix}ו${w}`;
  return `${prefix}${w}`;
}

/** הקיצור הנפוץ ביותר: "בעיר" */
export const inHe = (word: string): string => hePrefix('ב', word);
