/**
 * רשת ביטחון דטרמיניסטית לכפתורי תשובה מהירה, לתרחיש יעד לא מכוסה.
 *
 * ## למה זה קיים
 *
 * agentPrefix.ts כבר מורה למודל לצרף suggest_quick_replies כשהוא מציע
 * לחקור יעד לא מכוסה ("כן, לחקור" / "יעד אחר"). בדיקה חיה הראתה שזה לא
 * נאכף באמינות - שני תורים מתוך חמישה בדיוק חסרו כפתורים לגמרי, למרות
 * הודעה שמפורשות מציעה "רוצה שאנסה לחקור, או שתעדיף יעד אחר?". זו אותה
 * מסקנה שכבר נכתבה עבור priceGuard: כשהמודל מתעלם מכלל, לא מנסחים אותו
 * חזק יותר - מזיזים אותו למקום שהוא לא בחירה.
 *
 * ## למה זה לא priceGuard
 *
 * priceGuard **חותך** טענות לא מגובות - כישלון שם הוא בטוח (עדיף
 * להחסיר עובדה מלהמציא אחת). כאן ההפך: התוספת היא רק **הוספה** של
 * כפתורים כשהם חסרים, ולעולם לא הסרה של תוכן. False positive במקרה
 * הזה הוא כפתורים מיותרים שמישהו יכול פשוט להתעלם מהם - לא מידע שגוי
 * שיוצא למטייל. זה מה שמאפשר תבנית זיהוי סבירה יחסית בלי הקפדה קיצונית
 * על false positives, בניגוד לחיתוך תוכן.
 *
 * ## מתי זה מתערב
 *
 * רק כשהתשובה כבר מזכירה גם "לא מכוסה/בקטלוג" וגם "לחקור" (סימן שהמודל
 * *כבר* בתהליך של הצעת החקירה האוטומטית, לא שאלה כללית אחרת על כיסוי),
 * וכשהמודל עצמו לא צירף אף תשובה מהירה. אף פעם לא דורס תשובות שהמודל
 * כן סיפק.
 */

const NOT_COVERED =
  /(לא|אינ[הו]|אין)\s.{0,25}(בקטלוג|במאגר|ברשימת\s*היעדים|היעדים\s*המכוסים|היעדים\s*המאומתים)/;
const OFFERS_EXPLORE = /לחקור/;

/** ברירת המחדל - תואם בטון וניסוח למה שהמודל עצמו נוטה להציע */
export const FALLBACK_UNCOVERED_REPLIES = ['כן, לנסות לחקור', 'יעד אחר', 'רק שאלתי'];

/**
 * מחזיר כפתורי ברירת מחדל כשהתשובה נראית כמו הצעת חקירה ליעד לא מכוסה
 * בלי שהמודל צירף suggest_quick_replies בעצמו, אחרת null.
 */
export function fallbackUncoveredQuickReplies(fullText: string): string[] | null {
  if (!NOT_COVERED.test(fullText) || !OFFERS_EXPLORE.test(fullText)) return null;
  return FALLBACK_UNCOVERED_REPLIES;
}
