#!/usr/bin/env bash
# Installs or updates the tiyul+ database stack (compose.yml) on the VPS.
# Idempotent: rerun it after changing anything in deploy/db/. Run by
# `npm run deploy -- db`, as root, from an extracted copy of the repo.
#
#   1. /opt/tiyulplus-db with its secrets. Generated on the first run and never
#      again: a new JWT secret would sign every visitor out and invalidate the
#      app's keys, a new database password would lock the services out.
#   2. the containers, started and checked.
#   3. the nightly backup timer.
#   4. the Caddy block for db.tiyulplus.com - only once that name points here,
#      for the same ACME reason as deploy/cutover.sh.
set -euo pipefail

ROOT=/opt/tiyulplus-db
HERE=$(cd "$(dirname "$0")" && pwd)
REPO=$(cd "$HERE/../.." && pwd)
WEB_ENV=/opt/tiyulplus-web/shared/env
CF=/etc/caddy/Caddyfile
NODE=/opt/node24/bin/node

install -d -o root -g root -m 700 "$ROOT" "$ROOT/backups"
install -d -o root -g root -m 755 "$ROOT/init" "$ROOT/templates"

# ---- 1. secrets -------------------------------------------------------------
envf=$ROOT/.env
if [ ! -f "$envf" ]; then
  install -o root -g root -m 600 /dev/null "$envf"
  jwt=$(openssl rand -hex 32)
  {
    echo "# Generated by install.sh on $(date -u +%F). Never regenerate: see install.sh."
    echo "POSTGRES_PASSWORD=$(openssl rand -hex 24)"
    echo "AUTHENTICATOR_PASSWORD=$(openssl rand -hex 24)"
    echo "AUTH_ADMIN_PASSWORD=$(openssl rand -hex 24)"
    echo "JWT_SECRET=$jwt"
    # The two API keys, the same shape as a Supabase project's legacy keys:
    # HS256 JWTs with a role claim, valid for ten years. ANON_KEY is public
    # (it ships in the browser bundle); SERVICE_ROLE_KEY bypasses row level
    # security and stays on the server.
    JWT_SECRET=$jwt "$NODE" -e '
      const c = require("node:crypto");
      const b = (o) => Buffer.from(JSON.stringify(o)).toString("base64url");
      const iat = Math.floor(Date.now() / 1000);
      for (const [name, role] of [["ANON_KEY", "anon"], ["SERVICE_ROLE_KEY", "service_role"]]) {
        const body = b({ alg: "HS256", typ: "JWT" }) + "." + b({ role, iss: "supabase", iat, exp: iat + 10 * 365 * 86400 });
        const sig = c.createHmac("sha256", process.env.JWT_SECRET).update(body).digest("base64url");
        console.log(`${name}=${body}.${sig}`);
      }'
  } >> "$envf"
  echo "generated new secrets in $envf"
fi

# Copied from the website's env file on every run, so a rotated key there is
# picked up here: the SMTP password is the Resend key, and Google sign-in must
# accept tokens issued to the same client id the site's button uses.
setkv() { # setkv KEY VALUE - replace or append, without the value touching argv of sed
  local tmp; tmp=$(mktemp)
  grep -v "^$1=" "$envf" > "$tmp" || true
  printf '%s=%s\n' "$1" "$2" >> "$tmp"
  install -o root -g root -m 600 "$tmp" "$envf"; rm -f "$tmp"
}
webval() { sed -n "s/^$1=//p" "$WEB_ENV" | tail -1; }
smtp=$(webval RESEND_API_KEY); gid=$(webval NEXT_PUBLIC_GOOGLE_CLIENT_ID)
[ -n "$smtp" ] || echo "!! RESEND_API_KEY is not in $WEB_ENV - login codes cannot be sent" >&2
[ -n "$gid" ] || echo "!! NEXT_PUBLIC_GOOGLE_CLIENT_ID is not in $WEB_ENV - Google sign-in is off" >&2
setkv SMTP_PASS "$smtp"
setkv GOOGLE_CLIENT_ID "$gid"

# ---- 2. the stack -----------------------------------------------------------
install -m 644 "$HERE/compose.yml" "$ROOT/compose.yml"
install -m 755 "$HERE/init/00-roles.sh" "$ROOT/init/00-roles.sh"
install -m 755 "$HERE/backup.sh" "$HERE/import-supabase.sh" "$ROOT/"
install -m 644 "$REPO/emails/auth-magic-link.html" "$ROOT/templates/auth-magic-link.html"

dc() { docker compose --project-directory "$ROOT" -f "$ROOT/compose.yml" "$@"; }
dc pull --quiet
dc up -d --remove-orphans --wait --wait-timeout 180

for _ in $(seq 1 60); do
  curl -fsS -m 3 -o /dev/null http://127.0.0.1:4811/health 2>/dev/null &&
    [ "$(curl -s -m 3 -o /dev/null -w '%{http_code}' http://127.0.0.1:4810/)" != 000 ] && break
  sleep 1
done
curl -fsS -m 3 -o /dev/null http://127.0.0.1:4811/health || { dc logs --tail 50 auth >&2; exit 1; }
echo "database stack up: rest 127.0.0.1:4810, auth 127.0.0.1:4811"
docker stats --no-stream --format '  {{.Name}}: {{.MemUsage}}' $(dc ps -q)

# ---- 3. backups -------------------------------------------------------------
install -m 644 "$HERE/tiyulplus-db-backup.service" "$HERE/tiyulplus-db-backup.timer" /etc/systemd/system/
systemctl daemon-reload
systemctl enable --now tiyulplus-db-backup.timer >/dev/null

# ---- 4. Caddy ---------------------------------------------------------------
IP=${VPS_IP:-$(ip -4 route get 1.1.1.1 | sed -n 's/.* src \([0-9.]*\).*/\1/p')}
# Asks the zone's own nameservers, as cutover.sh does: a resolver cache can
# answer with an old address for the length of the TTL.
if "$NODE" -e '
  const dns = require("node:dns").promises;
  (async () => {
    const ns = await dns.resolveNs("tiyulplus.com");
    const r = new dns.Resolver();
    r.setServers((await Promise.all(ns.map((n) => dns.resolve4(n).catch(() => [])))).flat());
    const a = await r.resolve4("db.tiyulplus.com").catch(() => []);
    process.exit(a.length === 1 && a[0] === process.argv[1] ? 0 : 1);
  })().catch(() => process.exit(1));' "$IP"; then
  cp -a "$CF" "$CF.bak-tiyulplus-db-$(date +%Y%m%d-%H%M%S)"
  tmp=$(mktemp)
  # Everything outside this script's markers stays byte-for-byte as it was.
  awk '/^# >>> tiyul\+ database/{skip=1} !skip{print} /^# <<< tiyul\+ database/{skip=0}' "$CF" > "$tmp"
  { printf '\n'; cat "$HERE/Caddyfile.tiyulplus-db"; } >> "$tmp"
  caddy validate --adapter caddyfile --config "$tmp" >/dev/null
  install -m 644 -o root -g root "$tmp" "$CF"; rm -f "$tmp"
  systemctl reload caddy
  for _ in $(seq 1 24); do
    curl -fsS -m 10 -o /dev/null --resolve db.tiyulplus.com:443:127.0.0.1 \
      https://db.tiyulplus.com/auth/v1/health 2>/dev/null && {
      echo "https://db.tiyulplus.com is served from this box"; exit 0; }
    sleep 5
  done
  echo "!! no valid HTTPS answer from db.tiyulplus.com after 2 minutes - journalctl -u caddy -n 100" >&2
  exit 1
else
  echo "db.tiyulplus.com does not point at $IP yet - add the A record, then rerun to install the Caddy block"
fi
