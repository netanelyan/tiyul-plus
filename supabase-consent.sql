-- שמופיע כ"עודכן לאחרונה" בעמוד /terms בזמן האישור (ראו
-- src/lib/legal.ts). לא נדרס בכניסה חוזרת - הקוד כותב את זה פעם אחת,
-- בהתחברות הראשונה שבה עוד לא נרשמה הסכמה עבור אותו חשבון.
